// Обяснение на гласуване по заглавието му. Работи за всички гласувания,
// без да измисля съдържание: казва какъв тип е гласуването и какво следва от „за“ и „против“.
// Конкретното съдържание на закона идва от редакционните обяснения в data/laws.json.

import { MPS, partyName } from "./parliament";

export type Explanation = {
  kind: string;          // кратък етикет
  what: string;          // какво се гласува
  ifYes: string;         // какво следва при приемане
  ifNo: string;          // какво следва при отхвърляне
  proposer?: { name: string; party?: string; id?: number };
  law?: { name: string; slug: string };
};

const LAW_RE = /(?:ЗИД на |Законопроект за изменение(?: и допълнение)? на |Законопроект за )?(Закона? за [^–\-,]+?)(?:\s+[–-]\s+|\s*$)/;

export function lawFromTitle(title: string): { name: string; slug: string } | undefined {
  if (!/закон/i.test(title)) return undefined;
  const m = title.match(LAW_RE);
  if (!m) return undefined;
  let name = m[1].trim().replace(/^Закона/, "Закон");
  name = name.replace(/\s+(първо|второ)\s+гласуване.*$/i, "").trim();
  const slug = translit(name.toLowerCase().replace(/^закон за\s+/, ""))
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return { name, slug };
}

const TR: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ж: "zh", з: "z", и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p",
  р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "ts", ч: "ch", ш: "sh", щ: "sht", ъ: "a", ь: "y", ю: "yu", я: "ya",
};
export const translit = (s: string) => [...s].map((c) => TR[c] ?? c).join("");

function findMp(fullName: string) {
  const parts = fullName.trim().split(/\s+/);
  const first = parts[0], last = parts.at(-1)!;
  return MPS.find((m) => m.name.startsWith(first + " ") && m.name.endsWith(" " + last));
}

export function explain(title: string, outcome: string): Explanation {
  const t = title;
  const law = lawFromTitle(t);
  const passed = outcome !== "rejected";

  const propMatch = t.match(/предложение от ([А-ЯЁЙ][а-яёй]+(?:\s+[А-ЯЁЙ][а-яёй-]+){1,2})/);
  const procMatch = t.match(/процедура от ([А-ЯЁЙ][а-яёй]+(?:\s+[А-ЯЁЙ][а-яёй-]+){1,2})/);
  const who = propMatch?.[1] ?? procMatch?.[1];
  const mp = who ? findMp(who) : undefined;
  const proposer = who ? { name: who, party: mp ? partyName(mp.party) : undefined, id: mp?.id } : undefined;
  const byWhom = proposer ? `${proposer.name}${proposer.party ? ` (${proposer.party})` : ""}` : "депутат";

  if (/пряко предаване|БНТ/i.test(t)) {
    return { kind: "Процедура: пряко излъчване", law, proposer,
      what: `${byWhom} предлага обсъждането да се предава на живо по БНТ.`,
      ifYes: "Дебатът се излъчва по националната телевизия.",
      ifNo: "Дебатът продължава без пряко излъчване. Записът и стенограмата остават публични." };
  }
  if (/удължаване на срока за предложения/i.test(t)) {
    return { kind: "Процедура: срок за предложения", law, proposer,
      what: `${byWhom} предлага повече време депутатите да внасят промени между първо и второ четене.`,
      ifYes: "Срокът за писмени предложения се удължава, обикновено до три седмици.",
      ifNo: "Остава обичайният срок (7 дни). Законът стига по-бързо до второ четене." };
  }
  if (/съкращаване на срока/i.test(t)) {
    return { kind: "Процедура: по-кратък срок", law, proposer,
      what: `${byWhom} предлага по-кратък срок за предложения между първо и второ четене.`,
      ifYes: "Законът минава по-бързо, но остава по-малко време за обсъждане и становища.",
      ifNo: "Остава обичайният срок за предложения." };
  }
  if (/двете гласувания в едно заседание|две гласувания/i.test(t)) {
    return { kind: "Процедура: двете четения наведнъж", law, proposer,
      what: "Предложение законът да се приеме на първо и второ четене в едно заседание.",
      ifYes: "Законът се приема окончателно още днес, без отделен срок за предложения.",
      ifNo: "Второто четене ще е в друго заседание след срок за предложения." };
  }
  if (/[Пп]рограма за работата/.test(t)) {
    return { kind: "Процедура: програма", proposer,
      what: proposer ? `${byWhom} предлага промяна в програмата на парламента за седмицата.` : "Гласува се програмата на парламента за седмицата.",
      ifYes: proposer ? "Темата влиза в програмата и ще бъде разгледана." : "Програмата е приета и по нея се работи.",
      ifNo: proposer ? "Темата не влиза в програмата за тази седмица." : "Програмата не е приета." };
  }
  if (/[Рр]атифи/.test(t)) {
    return { kind: "Ратификация", proposer,
      what: "Парламентът одобрява международен договор, който България е подписала. Без това одобрение договорът не важи за страната.",
      ifYes: "Договорът става задължителен за България.",
      ifNo: "Договорът не влиза в сила за България." };
  }
  if (/[Рр]ешение за (избиране|освобождаване|приемане на оставка)|избор на/.test(t)) {
    return { kind: "Избор или освобождаване", proposer,
      what: "Решение кой да заеме или да напусне длъжност, която зависи от парламента.",
      ifYes: "Решението влиза в сила.",
      ifNo: "Лицето не е избрано или не е освободено." };
  }
  if (/първо гласуване/.test(t)) {
    return { kind: "Първо четене", law, proposer,
      what: "Гласува се законопроектът по принцип: дали идеята му е приемлива. Подробностите ще се гласуват текст по текст на второ четене.",
      ifYes: "Законопроектът продължава. Депутатите имат срок да предлагат промени, после следва второ четене.",
      ifNo: "Законопроектът отпада и не може да бъде внесен отново в същия вид скоро." };
  }
  if (/второ гласуване/.test(t)) {
    const par = t.match(/параграф[ие]?\s+([\dа-я]+(?:\s*(?:и|до)\s*(?:параграф\s+)?[\dа-я]+)?)/i)?.[1];
    if (propMatch && /за редакция/.test(t)) {
      return { kind: "Второ четене: редакция от залата", law, proposer,
        what: `${byWhom} предлага от трибуната друга формулировка${par ? ` на § ${par}` : ""}. Обикновено е уточнение на текста, а не нова идея. Гласува се преди основния текст.`,
        ifYes: "Текстът се гласува с новата формулировка.",
        ifNo: "Остава формулировката от доклада на комисията." };
    }
    if (propMatch) {
      return { kind: "Второ четене: предложение на депутат", law, proposer,
        what: `${byWhom} предлага своя редакция${par ? ` на § ${par}` : ""}. Това е предложение, което водещата комисия не е подкрепила, затова се гласува отделно в залата.`,
        ifYes: "Текстът на закона се променя според предложението.",
        ifNo: "Предложението отпада. Гласува се текстът във вида, предложен от комисията." };
    }
    if (/наименование/.test(t)) {
      return { kind: "Второ четене: наименование", law,
        what: "Гласува се наименованието на закона или на раздела.",
        ifYes: "Наименованието е прието.", ifNo: "Наименованието не е прието." };
    }
    if (/- нов|– нов/.test(t)) {
      return { kind: "Второ четене: нов текст", law,
        what: `Гласува се нов текст${par ? ` (§ ${par})` : ""}, който не е бил в първоначалния законопроект. Обикновено е добавен от комисията между първо и второ четене.`,
        ifYes: "Новият текст става част от закона.", ifNo: "Новият текст не влиза в закона." };
    }
    return { kind: "Второ четене: текст на закона", law,
      what: `Гласува се конкретен текст от закона${par ? ` (§ ${par})` : ""}. На второ четене всеки параграф се гласува отделно.`,
      ifYes: "Текстът става част от окончателния закон.",
      ifNo: "Текстът отпада от закона. Често това значи, че комисията е предложила да не се приема в първоначалния вид." };
  }
  if (/[Бб]юджет/.test(t)) {
    return { kind: "Бюджет", law, proposer,
      what: "Гласуване, свързано с държавния бюджет: приходи, разходи, дълг или трансфери.",
      ifYes: "Предложеното разпределение на парите е прието.", ifNo: "Предложението не е прието." };
  }
  if (/[Пп]роцедура|[Пп]роцедурно/.test(t)) {
    return { kind: "Процедура", law, proposer,
      what: `${proposer ? byWhom + " прави" : "Направено е"} процедурно предложение за начина на работа в залата.`,
      ifYes: "Работата продължава по предложения начин.", ifNo: "Работата продължава както досега." };
  }
  if (/^Решение/.test(t)) {
    if (propMatch) {
      return { kind: "Решение: предложение за редакция", proposer,
        what: `${byWhom} предлага друга формулировка на решението на парламента.`,
        ifYes: "Решението се приема с предложената формулировка.",
        ifNo: "Предложената формулировка отпада. Гласува се основният текст." };
    }
    return { kind: "Решение на парламента", proposer,
      what: "Решение на Народното събрание. То не е закон, но задължава институциите, възлага задача или определя действие (например преговори, разрешение, отчет).",
      ifYes: "Решението влиза в сила и институциите трябва да го изпълнят.",
      ifNo: "Решението не е прието и не поражда действие." };
  }
  return { kind: law ? "Закон" : "Друго", law, proposer,
    what: "Заглавието в стенограмата не казва достатъчно за вида на гласуването. Вижте стенограмата за подробности.",
    ifYes: passed ? "Прието." : "Ако беше прието, решението щеше да влезе в сила.",
    ifNo: passed ? "Ако беше отхвърлено, решението нямаше да влезе в сила." : "Отхвърлено." };
}
