// Колко силна е връзката „изпълнител ↔ политик“ за флага в риска. Данните са съвпадения по три имена (Наясно, по ТР и декларациите).
//  2: силна — депутат, който е собственик или управител на частна фирма, или длъжностно лице, което само е посочило фирмата в декларацията си;
//  1: възможна — длъжностно лице със собственост по ТР, само по съвпадение на имената (може да е съименник);
//  0: няма личен интерес — включително държавни и общински дружества, където управителят и „действителният собственик“ по закон са назначени лица.
// Държавно или общинско дружество разпознаваме по това, че Наясно е отбелязало хора от ръководството му като „ръководство на държавно дружество“.
const EQUITY = ["съдружник", "едноличен собственик", "дял в капитала", "действителен собственик"];
const MANAGE = ["управител / директор", "управител", "представител", "прокурист"];
const has = (l, list) => (l.roles ?? []).some((r) => list.some((x) => r.startsWith(x)));
/** Държавно или общинско дружество: Наясно е отбелязало хора от ръководството му като „ръководство на държавно дружество“. */
export const isPublicFirm = (links) => links.some((l) => l.position === "ръководство на държавно дружество");
export function politicalStrength(links) {
  if (!links?.length) return 0;
  if (isPublicFirm(links)) return 0; // вкл. декларациите на самите назначени ръководители
  if (links.some((l) => (l.roles ?? []).includes("посочено в декларация"))) return 2;
  if (links.some((l) => l.kind === "mp" && (has(l, EQUITY) || has(l, MANAGE)))) return 2;
  if (links.some((l) => l.kind === "official" && has(l, EQUITY))) return 1;
  return 0;
}
