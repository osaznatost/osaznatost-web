import { describe, expect, it } from "vitest";
import { explain, lawFromTitle } from "./voteExplain";

describe("обяснение на гласуване", () => {
  it("разпознава закона и предложение на депутат", () => {
    const e = explain("ЗИД на Закона за управление на отпадъците - второ гласуване - параграф 16 - предложение от Петър Петров", "rejected");
    expect(e.law?.slug).toBe("upravlenie-na-otpadatsite");
    expect(e.kind).toBe("Второ четене: предложение на депутат");
    expect(e.proposer?.party).toBe("Възраждане");
    expect(e.what).toContain("§ 16");
  });
  it("първо четене", () => {
    expect(explain("ЗИД на Закона за управление на отпадъците – първо гласуване", "passed").kind).toBe("Първо четене");
    expect(lawFromTitle("ЗИД на Закона за управление на отпадъците – първо гласуване")?.name).toBe("Закон за управление на отпадъците");
  });
  it("процедура за срок", () => {
    expect(explain("ЗИД на Закона за здравето – първо гласуване - процедура от Георги Илиев за удължаване на срока за предложения", "passed").kind).toBe("Процедура: срок за предложения");
  });
  it("ратификация", () => {
    expect(explain("Ратификация на Спогодбата за въздушни съобщения", "passed").kind).toBe("Ратификация");
  });
});

describe("редакция от залата", () => {
  it("не твърди, че комисията е против", () => {
    const e = explain("ЗИД на Закона за акцизите и данъчните складове - второ гласуване - параграф 1 - предложение от Светла Коджабашева за редакция", "passed");
    expect(e.kind).toBe("Второ четене: редакция от залата");
  });
  it("бюджетът се разпознава като закон", () => {
    expect(explain("Закон за държавния бюджет на Република България за 2026 г. - второ гласуване - член 1", "passed").law?.slug).toBe("darzhavniya-byudzhet-na-republika-balgariya-za-2026-g");
  });
});
